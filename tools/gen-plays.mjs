// Generates the play scripts that win whole deals (tests/native/journey-1.play and
// tests/native/practice-2d-phone.play) from the deal generator's certificate (js/solver.js
// generateWinnableLayout: the forward commands that solve the deal), replayed through the rules to
// name each card the player presses: draws are the D key; a move is a click on the card, then on its
// foundation (the 3D table's named targets) or two quick touches on it (the 2D table's double tap).
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createCustomGame, applyCommand, rankOf, suitOf } from '../js/rules.js';
import { generateWinnableLayout } from '../js/solver.js';
import { JOURNEY, practiceDeal } from '../js/content.js';

const RANKS = ['Ace', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Jack', 'Queen', 'King'];
const SUITS = ['Spades', 'Hearts', 'Diamonds', 'Clubs'];
const name = (c) => `${RANKS[rankOf(c)]} of ${SUITS[suitOf(c)]}`;
const foundation = (state, f) => {
  const p = state.foundations[f];
  return p.length ? `${name(p[p.length - 1])}, Foundation ${SUITS[f]}` : `Foundation ${SUITS[f]}`;
};

/** The deal's steps as play-script lines. */
function steps(descriptor, style) {
  const { layout, certificate } = generateWinnableLayout(descriptor.seed, descriptor.ruleset);
  let state = createCustomGame(layout, descriptor.ruleset, descriptor.seed);
  const out = [];
  let n = 0;
  for (const cmd of certificate) {
    if (cmd.type === 'draw') out.push('key KeyD 1', 'frames 20');
    else {
      const from = cmd.from.zone === 'waste' ? state.waste[state.waste.length - 1] : state.tableau[cmd.from.pile].at(-1).c;
      if (style === 'click') out.push(`click =${name(from)}`, 'frames 5', `click =${foundation(state, cmd.to.pile)}`, 'frames 25');
      else out.push(`touch =${name(from)}`, 'frames 2', `touch =${name(from)}`, 'frames 25');
    }
    const r = applyCommand(state, { ...cmd, id: `g${++n}` });
    if (!r.ok) throw new Error(`certificate step ${n} refused: ${r.error}`);
    state = r.state;
  }
  if (state.status !== 'won') throw new Error('the certificate did not win');
  return out;
}

const journey = [
  '# Generated by tools/gen-plays.mjs: Journey stage 1 ("First Sprouts") won on the 3D table on a desktop,',
  '# by the mouse on the named card and foundation targets (draws by the D key), to its results.',
  '# viewport 1280x800@1',
  'until 600 Patience',
  'frames 10',
  'click =Journey',
  'until 120 The Journey',
  'frames 10',
  'click =Stage 1: First Sprouts. Unlocked.',
  'until 300 banked',
  'frames 60',
  'save journey-deal',
  ...steps(JOURNEY[0], 'click'),
  'until 300 The garden blooms',
  'frames 60',
  'expect First Sprouts — complete',
  'expect Journey: 1/40 stages',
  'save journey-results',
  'click =Next: Sunlit Rows',
  'until 300 banked',
  'frames 30',
  'expect Journey',
  '',
];
writeFileSync(new URL('../tests/native/journey-1.play', import.meta.url), journey.join('\n'));

